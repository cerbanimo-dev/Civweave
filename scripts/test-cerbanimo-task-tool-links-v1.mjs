import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
import {toolsForTask,toolHref} from '../public/app/cerbanimo-task-tool-links-v1.mjs';

const quest={id:'quest:private-42'};
const kinds=task=>toolsForTask(quest,{id:'task:1',status:'ready',...task}).map(row=>row.kind);

assert.deepEqual(kinds({title:'Draft the launch proposal'}),['text']);
assert.deepEqual(kinds({title:'Write 500 words about what you learned'}),['text'],'strong text-production verbs should work without a file-type noun');
assert.deepEqual(kinds({title:'Record the podcast introduction'}),['audio']);
assert.deepEqual(kinds({title:'Mix and master the finished take'}),['audio'],'strong audio-production verbs should work without an audio noun');
assert.deepEqual(kinds({title:'Edit the launch video'}),['video']);
assert.deepEqual(kinds({title:'Film yourself demonstrating the technique'}),['video'],'strong video-production verbs should work without a video noun');
assert.deepEqual(kinds({title:'Write the script and record the voiceover'}),['text','audio']);
assert.deepEqual(kinds({title:'Watch the required video'}),[],'passive video consumption must not expose the Video Creator');
assert.deepEqual(kinds({title:'Review the article'}),[],'passive review must not expose the Text Creator');
assert.deepEqual(kinds({title:'Research podcast formats'}),[],'research about a medium is not a media deliverable');
assert.deepEqual(kinds({title:'Listen to the recording'}),[],'passive listening must not expose the Audio Creator');
assert.deepEqual(kinds({title:'Revise the article'}),['text']);
assert.deepEqual(kinds({title:'Draft the memo',status:'completed'}),[],'completed work should not receive a creation shortcut');
assert.deepEqual(kinds({title:'Collect references',creatorTools:['text']}),['text'],'explicit Creator tool hints remain available for future task producers');

assert.deepEqual(kinds({title:'Inspect supplied DOCX for document structure'}),['wordcraft'],'real WordCraft capability should be offered for inspection');
assert.deepEqual(kinds({title:'Extract text from ODT file'}),['wordcraft'],'WordCraft extraction should be routed from explicit file-format tasks');
assert.deepEqual(kinds({title:'Inspect the floor plan drawing in DXF'}),['cadcraft'],'CADCraft should be discoverable for supported drawing inspection');
assert.deepEqual(kinds({title:'Export this DWG drawing as SVG'}),['cadcraft'],'CAD export workflow should route to CADCraft');
assert.deepEqual(kinds({title:'Build a 3D CAD model from scratch'}),[],'do not offer file-only CAD inspection as though it creates models');
assert.deepEqual(kinds({title:'Research CAD drafting tools'}),[],'research tasks should not open native-file processors');
assert.deepEqual(kinds({title:'Make a spreadsheet budget'}),[],'GridCraft integration is cataloged but not executable');
assert.deepEqual(kinds({title:'Review notes'}),[],'unrelated notes should not trigger document ingestion');
assert.deepEqual(kinds({title:'Create a CAD poster',toolHints:['cadcraft']}),['cadcraft'],'explicit tool hints remain supported even when the automatic heuristic is conservative');
assert.deepEqual(kinds({title:'Inspect the PDF before submission'}),['pdfcraft'],'PDF inspection needs the PdfCraft action');
assert.deepEqual(kinds({title:'Combine two PDF documents into one'}),['pdfcraft'],'PDF merging routes to the working PDF connector');
assert.deepEqual(kinds({title:'Sign this PDF digitally'}),[],'there is no signature tool in the initial PdfCraft bridge');
assert.deepEqual(kinds({title:'Discuss how PDFs work'}),[],'passive PDF discussion should not launch a file processor');
const officeHref=toolHref('wordcraft',quest.id,'task:private-7');
assert.match(officeHref,/^\/creator-suite\/tools\.html\?tool=wordcraft/);
assert.match(officeHref,/quest=quest%3Aprivate-42/);
assert.equal(officeHref.includes('proposal'),false,'document content must not be placed into a cross-page URL');
const pdfHref=toolHref('pdfcraft',quest.id,'task:private-7');
assert.match(pdfHref,/^\/creator-suite\/tools\.html\?tool=pdfcraft/);
const cadHref=toolHref('cadcraft',quest.id,'task:private-7');
assert.match(cadHref,/^\/creator-suite\/tools\.html\?tool=cadcraft/);
assert.throws(()=>toolHref('gridcraft',quest.id,'task:private-7'),/Unsupported Creator Suite task tool/,'catalog-only GridCraft must not become an executable task link');

const href=toolHref('video',quest.id,'task:private-7');
assert.match(href,/^\/creator-suite\/\?tool=video/);
assert.match(href,/quest=quest%3Aprivate-42/);
assert.match(href,/task=task%3Aprivate-7/);
assert.equal(href.includes('launch'),false,'task wording must not be copied into Creator Suite URLs');
assert.throws(()=>toolHref('image',quest.id,'task:1'),/Unsupported Creator Suite task tool/);

const engineSource=await fs.readFile(new URL('../public/app/cerbanimo-quest-engine-v144.js',import.meta.url),'utf8');
const engineContext=vm.createContext({structuredClone});
