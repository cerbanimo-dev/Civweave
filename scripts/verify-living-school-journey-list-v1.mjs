import assert from'node:assert/strict';
import fs from'node:fs';
import{execFileSync}from'node:child_process';
import{learningJourneySnapshot,PLAN_KEY,QUEUE_KEY,LEARNING_PLAN_SCHEMA}from'../public/app/cabinets/living-school/living-school-journey-index-v1.mjs';

const read=path=>fs.readFileSync(new URL('../'+path,import.meta.url),'utf8');
for(const file of [
 'public/app/cabinets/living-school/living-school-journey-index-v1.mjs',
 'public/app/cabinets/living-school/living-school-cleanroom-render-v218.mjs',
 'public/app/cabinets/living-school/living-school-cleanroom-v218.mjs']){
 execFileSync(process.execPath,['--check',file],{encoding:'utf8'});
}
const renderer=read('public/app/cabinets/living-school/living-school-cleanroom-render-v218.mjs');
const controller=read('public/app/cabinets/living-school/living-school-cleanroom-v218.mjs');
const records=new Map();
const store=(key,data)=>records.set(key,structuredClone(data));
const fetch=(key,fallback)=>records.has(key)?records.get(key):fallback;
const snapshot=state=>learningJourneySnapshot(fetch,state);
const title='Use And Memorize The Tarot',capability='use and memorize the tarot';
const plan={schema:LEARNING_PLAN_SCHEMA,id:'learning-plan-tarot',state:'review',updatedAt:'2026-10-24T22:00:00Z',
 request:{title,capability,count:4,intent:'new',mode:'guided',level:'beginner',proof:'Read one card independently'},
 modules:[{title:'The deck'},{title:'The major arcana'},{title:'Suit meanings'},{title:'Practice'}]};
const original={activePathId:'garden',pathContext:{id:'garden',title:'Garden Fundamentals and Community Organizing',capability:'garden planning'}};
assert.equal(snapshot(original).rows.length,0,'Routed intention alone must not imply a saved curriculum');
store(PLAN_KEY,plan);
let view=snapshot(original);
assert.equal(view.rows[0].status,'Review required');
assert.equal(view.retry,null,'An unapproved plan cannot be generated');
assert.equal(view.focus,null,'Unapproved REVIEW plans must not silently populate the generation form');
const approved={...plan,state:'approved',approvedAt:'2026-10-24T22:02:00Z',updatedAt:'2026-10-24T22:02:00Z'};
store(PLAN_KEY,approved);
view=snapshot(original);
assert.equal(view.rows[0].status,'Approved · curriculum not generated');
assert.equal(view.focus.title,title,'Approved Moss plan must take priority over stale garden pathContext');
assert.equal(view.focus.capability,capability);
assert.equal(view.retry.id,'plan:learning-plan-tarot');
assert.equal(view.retry.request.capability,capability);
store(QUEUE_KEY,{...approved.request,approvedPlanId:plan.id,approvedAt:approved.approvedAt,autoRun:true,queuedAt:'2026-10-24T22:03:00Z'});
view=snapshot(original);
assert.equal(view.rows.length,1,'Approved and queued same plan must not create duplicate entries');
assert.equal(view.rows[0].status,'Approved · select to generate','Legacy autoRun entries must remain manual after startup');
const report={status:'failed',requestId:'failed-tarot-1',request:{title,capability,count:4},updatedAt:'2026-10-24T22:04:00Z',unstructured:{error:'Qwen runtime cancelled'}};
assert.equal(snapshot({...original,generationRecovery:report}).focus.capability,capability,'Failed curriculum goal must prefill the form for an accurate retry');
view=snapshot({...original,generationRecovery:report});
assert.equal(view.rows.length,1,'Matched recovery should attach to approved plan');
assert.match(view.rows[0].status,/Generation failed/);
assert.match(view.rows[0].details,/cancelled/);
assert.ok(view.retry,'Failed approved curriculum still needs retry');
const partial={id:'curriculum-partial',title,capability,requestedModuleCount:4,modules:[{id:'one'}],updatedAt:'2026-10-24T22:05:00Z'};
view=snapshot({...original,school:partial,generationRecovery:{...report,status:'partial'}});
assert.ok(view.retry,'Partially created curriculum cannot consume approval');
assert.ok(view.rows.some(item=>item.status==='Partial curriculum'));
const complete={...partial,modules:[{id:'a'},{id:'b'},{id:'c'},{id:'d'}]};
view=snapshot({...original,school:complete});
assert.equal(view.retry,null,'Complete curriculum cannot be regenerated by stale approved plan');
assert.ok(view.rows.some(item=>item.status==='Curriculum ready'));
records.clear();
view=snapshot({...original,events:[{id:'failed-event',type:'living-school-new-path-replacement-rolled-back',at:'2026-10-24T22:06:00Z',detail:{title,capability,error:'Model cancelled'}}]});
assert.match(view.rows[0].status,/Generation failed/,'Rollback must remain visible after prior school restoration');
assert.match(view.rows[0].details,/Model cancelled/);
store(QUEUE_KEY,{...approved.request,approvedPlanId:plan.id,approvedAt:approved.approvedAt,autoRun:true,queuedAt:'2026-10-24T22:03:00Z'});
view=snapshot(original);
assert.equal(view.retry.id,'queue:learning-plan-tarot','Queued approved handoff must be recoverable even without REVIEW plan record');
assert.equal(view.rows[0].status,'Approved · generation awaits selection');
store(QUEUE_KEY,{...approved.request,approvedPlanId:plan.id,approvedAt:approved.approvedAt,autoRun:false,queuedAt:'2026-10-24T22:03:00Z'});
assert.equal(snapshot(original).retry.id,'queue:learning-plan-tarot','New manual-approved queue entries must remain selectable');
assert.match(renderer,/data-ls-journey-index="v1"/);
assert.match(renderer,/learningJourneySnapshot\(readJson,s\)/);
assert.match(renderer,/draft\?\.title\|\|s\.school\?\.title\|\|s\.pathContext/);
assert.match(renderer,/draft\?\.capability\|\|s\.school\?\.capability\|\|s\.pathContext/);
assert.match(renderer,/routeWins=Boolean/,'Explicit route selections must override stale form context');
assert.match(renderer,/learning-path-selected/,'Route precedence must reflect an actual click');
assert.match(renderer,/retry-approved-learning-journey/);
assert.match(renderer,/select-approved-learning-journey/,'Approved plan must be selected before generation is available');
assert.match(controller,/state\(\)\.settings\?\.selectedJourneyPlanId!==record\.id/,'Selection must be enforced before generation');
assert.match(controller,/async function retryApprovedLearningJourney/);
assert.match(controller,/record\.approvedAt/,'Retry requires proof of prior approval');
assert.match(controller,/await generateCurriculumFromChat\(request\)/,'Retry must go through the canonical curriculum engine');
assert.match(controller,/if\(school\.modules\.length<expected\|\|output\.generationRecovery\?\.status==='partial'\)/);
assert.match(controller,/localStorage\.removeItem\(PLAN_KEY\)/);
assert.match(controller,/living-school-new-path-replacement-rolled-back/);
assert.match(controller,/const attemptedRecovery=copy\(state\(\)\.generationRecovery\|\|null\)/);
assert.match(controller,/addEventListener\('storage'/);
console.log('PASS Living School saved journey list, approval, retry, rollback, partial and stale-path goal isolation');
