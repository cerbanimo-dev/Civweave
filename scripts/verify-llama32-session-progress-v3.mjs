import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const worker=readFileSync('public/app/local-ai/worker-v266.js','utf8');
const page=readFileSync('public/app/local-ai/llama32-two-pass-test-v3.html','utf8');
const dedicated=readFileSync('public/app/local-ai/llama32-diagnostic-worker-v3.js','utf8');
assert.match(dedicated,/phase\(id,'model-ready',started/,'Historical v3 probe must still report actual model readiness, not cached weight completion.');
// v4 is the currently active diagnostic and is asserted equal to the canonical
// inference worker below. v3 predates the Asyncify/chunked-cache revisions and
// should not be byte-identical to current source.
const beginning=worker.indexOf('function progressReporter(');
const end=worker.indexOf('function externalDataSetting(',beginning);
assert(beginning>=0&&end>beginning,'Could not extract the bounded worker progress reporter');
const reporterSource=worker.slice(beginning,end);
const received=[];
let clock=1000;
const scope={LLAMA32_COMPILER:'llama32-3b-instruct-q4f16',now:()=>clock,phase:(id,name,started,data)=>received.push({id,name,...data})};
vm.createContext(scope);
vm.runInContext(reporterSource+'\nthis.reporter=progressReporter;',scope);
const feed=scope.reporter('trial','loading-model',1000,{model:'llama32-3b-instruct-q4f16',backend:'webgpu'});
for(let i=0;i<10000;i++)feed({status:'progress',file:'onnx/model_q4f16.onnx_data',progress:100});
assert(received.length<=2,'10000 repeated weight callbacks must not flood the message channel');
assert(received.every(row=>row.progressOverall===null),'Model-file 100% cannot claim whole-model session readiness');
clock=2000;
feed({status:'done',file:'onnx/model_q4f16.onnx_data',progress:100});
assert(received.length<=3,'Done transition should be reported once');
for(let i=0;i<6000;i++)feed({status:'done',file:'onnx/model_q4f16.onnx_data_1',progress:100});
assert(received.length<=5,'Other large shards may complete without flooding');
assert.match(worker,/phase\(id,'model-ready',started/,'Only actual from_pretrained completion may emit ready');
assert.match(worker,/initializing-onnx-session/,'WebGPU session initialization must be separately visible');
assert.match(page,/new Worker\('\/app\/local-ai\/llama32-diagnostic-worker-v3\.js/);
const newestPage=readFileSync('public/app/local-ai/llama32-two-pass-test-v4.html','utf8');
const newestWorker=readFileSync('public/app/local-ai/llama32-diagnostic-worker-v4.js','utf8');
assert.equal(newestWorker,worker,'v4 diagnostic worker must use exactly the verified main runtime source');
assert.match(newestPage,/preflightAsyncify/);
assert.match(newestPage,/llama32-diagnostic-worker-v4\.js/);
assert.match(page,/if\(next==='model-ready'\)/,'UI must distinguish artifact percentage from actual session readiness');
assert.match(page,/printedAssets<25/,'UI must cap per-file progress logs');
assert.match(page,/old\.length>24000\?old\.slice\(-16000\)/,'Rendered diagnostic log must stay bounded');
assert.match(page,/sessionTicker=setInterval\(tick,1000\)/,'User must see session elapsed time');
assert.match(page,/timeoutMs=240000/,'Session test must time out rather than remain indefinitely stalled');
const js=page.match(/<script type="module">([\s\S]*?)<\/script>/)?.[1];
assert(js,'Expected inline module test script');
new Function(js.replace(/^import\s+.*;\s*$/gm,''));
console.log('PASS: 16000 redundant file callbacks produce <=5 messages; session readiness requires model-ready; v3 UI has bounded logs, timer, and watchdog.');
