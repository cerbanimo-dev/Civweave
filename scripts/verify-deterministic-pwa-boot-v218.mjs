import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const manifest=JSON.parse(await fs.readFile('public/app/manifest.webmanifest','utf8'));
assert(manifest.start_url.includes('installed=1'),'manifest start_url lacks installed marker');
for(const shortcut of manifest.shortcuts)assert(shortcut.url.includes('installed=1'),'shortcut lacks installed marker: '+shortcut.name);
const launcher=await fs.readFile('public/app/installed-entry-v146.js','utf8');
assert(launcher.includes('civweave.install-boundary.boot.v218'),'launcher lacks boot grant');
assert(launcher.includes("civweave:'/app/working-campus-v156.html'"),'launcher still uses fullscreen relay');
assert(launcher.includes("destination.searchParams.set('installed','1')"),'launcher drops installed marker');
const boundary=await fs.readFile('public/app/install-boundary-v146.js','utf8');
assert(boundary.includes('function explicitInstalled()'),'boundary lacks explicit installed grant');
assert(boundary.includes('civweave.install-boundary.boot.v218'),'boundary boot key mismatch');
const installer=await fs.readFile('public/install-v130.js','utf8');
assert(installer.includes("const ENTRY = '/app/?system=civweave&installed=1';"),'installer still opens legacy entry');
assert(installer.includes("const WORKER_SCRIPT_REVISION = 'compat-fullscreen-launch-v219';"),'installer worker revision mismatch');
const index=await fs.readFile('public/index.html','utf8');
assert(index.includes('revision=compat-fullscreen-launch-v219'),'homepage worker bootstrap mismatch');
console.log('Deterministic PWA boot v218 verified.');
