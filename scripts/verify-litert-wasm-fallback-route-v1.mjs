import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const route='functions/app/vendor/litert-lm/wasm/[file].js';
const source=await readFile(route,'utf8');
assert.match(source,/application\/wasm/);
assert.match(source,/env\.ASSETS\.fetch/);
assert.match(source,/ReadableStream/);
assert.doesNotMatch(source,/await\s+response\.arrayBuffer\(/);
const routeApi=await import(new URL('../'+route,import.meta.url));
const parts=['wasm/litertlm_wasm_asyncify_internal.wasm.part0','wasm/litertlm_wasm_asyncify_internal.wasm.part1'];
const bytes=[Uint8Array.from([0,97,115,109,1,0,0,0]),Uint8Array.from([35,49,55])];
let failPart=-1,loads=[];
const env={ASSETS:{fetch:async(request)=>{
  const path=new URL(request.url).pathname;loads.push(path);
  if(path.endsWith('/stage-manifest.json'))return new Response(JSON.stringify({omittedFiles:[{path:'wasm/litertlm_wasm_asyncify_internal.wasm',bytes:11,parts}]}),{headers:{'content-type':'application/json'}});
  const idx=parts.findIndex(part=>path.endsWith(part));
  if(idx<0)return new Response('<!doctype html>',{headers:{'content-type':'text/html'}});
  if(idx===failPart)return new Response('<!doctype html>',{headers:{'content-type':'text/html'}});
  return new Response(bytes[idx],{headers:{'content-type':'application/octet-stream'}});
}}};
const request=new Request('https://civweave-staging.pages.dev/app/vendor/litert-lm/wasm/litertlm_wasm_asyncify_internal.wasm');
const next=()=>new Response('static pass-through');
const ctx={request,env,params:{file:'litertlm_wasm_asyncify_internal.wasm'},next};
let r=await routeApi.onRequestGet(ctx);
assert.equal(r.status,200);
assert.equal(r.headers.get('content-type'),'application/wasm');
assert.equal(r.headers.get('content-length'),'11');
assert.deepEqual([...new Uint8Array(await r.arrayBuffer())],[...bytes[0],...bytes[1]]);
assert.deepEqual(loads.filter(path=>path.endsWith('.part0')||path.endsWith('.part1')).length,2);
r=await routeApi.onRequestHead({...ctx,request:new Request(request,{method:'HEAD'})});
assert.equal(r.status,200);assert.equal(r.body,null);
r=await routeApi.onRequestGet({...ctx,params:{file:'litertlm_wasm_internal.wasm'}});
assert.equal(await r.text(),'static pass-through');
failPart=1;
r=await routeApi.onRequestGet(ctx);
assert.equal(r.status,503,'a bad chunk must never stream HTML under a 200 WASM status');
console.log('PASS: bounded Asyncify LiteRT WASM chunks are reassembled in order as binary, HEAD works, and malformed assets fail closed.');
