import assert from 'node:assert/strict';
import {createStarlingLiveTurnManager as create} from '../public/app/shared/starling-live-turn-manager-v1.mjs';
let clock=10000;const emitted=[];
const m=create({hostId:'host',now:()=>clock,onEvent:e=>emitted.push(e),cooldownMs:5000,leaseMs:1000});
m.join({actorId:'host',participantId:'kami'});
m.join({actorId:'host',participantId:'maggie'});
m.join({actorId:'host',participantId:'human2',kind:'human'});
assert.equal(m.authorize({speakerId:'kami',turnId:'t1',leaseEpoch:1}),false);
assert.equal(m.grant({actorId:'host',speakerId:'kami',turnId:'t1'}).granted,false);
assert.equal(m.directedQuestion({actorId:'host',targetId:'kami',requestId:'q1'}).accepted,true);
assert.equal(m.snapshot().pending.length,1);
assert.equal(m.ask({actorId:'kami',requestId:'q1'}).accepted,false);
const lease=m.grant({actorId:'host',speakerId:'kami',turnId:'t1'}).lease;
assert.equal(m.authorize({speakerId:'kami',turnId:'t1',leaseEpoch:lease.epoch}),true);
assert.equal(m.grant({actorId:'host',speakerId:'maggie',turnId:'t2'}).granted,false);
assert.equal(m.ask({actorId:'maggie',requestId:'m1'}).accepted,true);
m.humanSpeech({actorId:'human2'});
assert.equal(m.authorize({speakerId:'kami',turnId:'t1',leaseEpoch:lease.epoch}),false);
assert.equal(m.grant({actorId:'host',speakerId:'kami',turnId:'t1b'}).granted,false);
const second=m.grant({actorId:'host',speakerId:'maggie',turnId:'t2'}).lease;
assert.ok(second);
clock+=1001;
assert.equal(m.authorize({speakerId:'maggie',turnId:'t2',leaseEpoch:second.epoch}),false);
assert.ok(emitted.some(e=>e.reason==='lease-expired'));
m.ask({actorId:'kami',requestId:'q2'});
m.emergencyMute({actorId:'host'});
assert.equal(m.snapshot().pending.length,0);
assert.equal(m.grant({actorId:'host',speakerId:'kami',turnId:'t3'}).granted,false);
m.resume({actorId:'host'});
m.ask({actorId:'kami',requestId:'q3'});
const third=m.grant({actorId:'host',speakerId:'kami',turnId:'t3'});
assert.equal(third.granted,false); // cooldown survives mute
clock+=5000;
assert.equal(m.grant({actorId:'host',speakerId:'kami',turnId:'t3'}).granted,true);
m.reconnect({actorId:'kami',participantId:'kami'});
assert.equal(m.authorize({speakerId:'kami',turnId:'t3',leaseEpoch:third.lease?.epoch}),false);
assert.equal(m.snapshot().pending.length,0);
assert.throws(()=>m.emergencyMute({actorId:'kami'}),/Host authority/);
assert.throws(()=>m.directedQuestion({actorId:'kami',targetId:'maggie',requestId:'x'}),/host/);
m.mute({actorId:'host',participantId:'maggie'});
assert.equal(m.ask({actorId:'maggie',requestId:'m2'}).accepted,false);
assert.equal(m.events().every(e=>e.schema==='civweave.starling-live-turn.v1'),true);
console.log('Starling live turn manager: 24 assertions passed');
