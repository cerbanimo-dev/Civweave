import {readFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=relative=>readFile(path.join(root,relative),'utf8');
const fail=message=>{throw new Error(message)};
const contract=JSON.parse(await read('config/release-contract.json'));
const {revision,policy,syncTag}=contract.offlineCampus||{};
if(!revision||!policy||!syncTag)fail('Release contract is incomplete.');
const wrapper=await read('public/service-worker-v203.js');
const override=await read('public/service-worker-offline-v211-override.js');
const expected=`/service-worker-offline-v211-override.js?v=${revision}&policy=${policy}`;
if(!wrapper.includes(expected))fail(`Active worker wrapper is not pinned to ${expected}.`);
if(!override.includes(`const V211_REVISION = '${revision}'`))fail('Offline revision does not match release contract.');
if(!override.includes(`const V211_POLICY = '${policy}'`))fail('Offline policy does not match release contract.');
if(!override.includes(`const V211_SYNC_TAG = '${syncTag}'`))fail('Offline sync tag does not match release contract.');
console.log(JSON.stringify({ok:true,revision,policy,syncTag,canonical:'config/release-contract.json'},null,2));
